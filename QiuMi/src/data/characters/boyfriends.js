export function getAllBoyfriends() {
  const all = []
  for (const key of Object.keys(boyfriends)) {
    for (const member of boyfriends[key].members) {
      all.push(member)
    }
  }
  return all
}

export function getBoyfriendById(id) {
  for (const key of Object.keys(boyfriends)) {
    const found = boyfriends[key].members.find(m => m.id === id)
    if (found) return found
  }
  return null
}
